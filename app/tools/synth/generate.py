"""Builds everything derived from sounds.json: haptic files, TypeScript maps, the spec's event table and the preview page."""
import base64
import html
import json
import re
from pathlib import Path

import numpy as np
import soundfile as sf

from loudness import active_loudness, peak_dbfs

ROOT = Path(__file__).resolve().parents[2]
CONFIG = json.loads((Path(__file__).parent / 'sounds.json').read_text())
SOUNDS = CONFIG['sounds']
EVENTS = CONFIG['events']
HEADER = '// Generated by tools/synth/generate.py from tools/synth/sounds.json. Edit that file, not this one.\n'


def write_ahap():
    folder = ROOT / 'assets' / 'haptics'
    folder.mkdir(parents=True, exist_ok=True)
    for name, signature in CONFIG['signatures'].items():
        spec = signature['ahap']
        pattern = []
        if 'curve' in spec:
            pattern.append({'Event': {
                'Time': 0, 'EventType': 'HapticContinuous', 'EventDuration': spec['duration'],
                'EventParameters': [
                    {'ParameterID': 'HapticIntensity', 'ParameterValue': 1.0},
                    {'ParameterID': 'HapticSharpness', 'ParameterValue': spec['sharpness']},
                ],
            }})
            pattern.append({'ParameterCurve': {
                'ParameterID': 'HapticIntensityControl', 'Time': 0,
                'ParameterCurveControlPoints': [{'Time': t, 'ParameterValue': v} for t, v in spec['curve']],
            }})
        for at, intensity, sharpness in spec.get('transients', []):
            pattern.append({'Event': {
                'Time': at, 'EventType': 'HapticTransient',
                'EventParameters': [
                    {'ParameterID': 'HapticIntensity', 'ParameterValue': intensity},
                    {'ParameterID': 'HapticSharpness', 'ParameterValue': sharpness},
                ],
            }})
        ahap = {'Version': 1.0, 'Metadata': {'Project': 'CleanScape', 'Description': signature['words']}, 'Pattern': pattern}
        (folder / f'{name}.ahap').write_text(json.dumps(ahap, indent=2) + '\n')
    android = {
        'predefined': CONFIG['android_predefined'],
        'waveforms': {name: s['android'] for name, s in CONFIG['signatures'].items()},
    }
    (folder / 'android-waveforms.json').write_text(json.dumps(android, indent=2) + '\n')


def write_typescript():
    folder = ROOT / 'src' / 'feedback'
    folder.mkdir(parents=True, exist_ok=True)
    events = {}
    for event in EVENTS:
        sound = event['sound']
        events[event['id']] = {
            'sound': sound,
            'defaultOn': sound in CONFIG['default_on'],
            'essential': event.get('essential', False),
            'volume': event.get('volume', 1),
            'cooldownMs': event.get('cooldown_ms', 0),
            'haptic': event['haptic'],
            'once': event.get('once', False),
            'skipHapticWhileTyping': event.get('skipHapticWhileTyping', False),
        }
    signatures = {name: s['steps'] for name, s in CONFIG['signatures'].items()}
    (folder / 'events.generated.ts').write_text(
        HEADER
        + f'export const FEEDBACK_EVENTS = {json.dumps(events, indent=2, ensure_ascii=False)} as const;\n\n'
        + f'export const SIGNATURES = {json.dumps(signatures, indent=2)} as const;\n'
    )
    for suffix, extension in (('', 'm4a'), ('.android', 'ogg')):
        lines = ''.join(
            f"  '{name}': require('../../assets/sounds/{name}.{extension}'),\n" for name in SOUNDS
        )
        (folder / f'sound-assets.generated{suffix}.ts').write_text(
            HEADER
            # ESLint only treats the Android file as ordinary code.
            + ('/* eslint-disable @typescript-eslint/no-require-imports */\n' if suffix else '')
            + f'export const SOUND_ASSETS = {{\n{lines}}} as const;\n'
        )


def recipe(event):
    haptic = event['haptic']
    if haptic.startswith('signature:'):
        name = haptic.split(':')[1]
        return f"{CONFIG['signatures'][name]['words']} (`{name}.ahap`, waveform `{name}`)"
    words = CONFIG['haptic_words'][haptic]
    android = CONFIG['android_predefined'].get(haptic)
    return f'{words} / `{android}`' if android else words


def write_spec_table():
    path = ROOT / 'docs' / 'sound-haptics-spec.md'
    rows = ['| Area | Event | ID | Sound | By default | Haptic: iOS / Android |', '|---|---|---|---|---|---|']
    for event in EVENTS:
        sound = event['sound']
        name = f"`{SOUNDS[sound]['name']}`" if sound else 'None'
        state = 'On' if sound in CONFIG['default_on'] else ('Off until "All sounds"' if sound else 'Silent')
        rows.append(f"| {event['area']} | {event['label']} | `{event['id']}` | {name} | {state} | {recipe(event)} |")
    added = [f"- **{e['label']}** (`{e['id']}`): {e['added']}" for e in EVENTS if 'added' in e]
    block = '\n'.join(rows + ['', 'Events added to the brief:', '', *added])
    text = path.read_text()
    text = re.sub(r'(<!-- events:start -->\n).*?(\n<!-- events:end -->)', lambda m: m.group(1) + block + m.group(2), text, flags=re.S)
    path.write_text(text)


def waveform(audio, bars=64):
    chunks = np.array_split(np.abs(audio), bars)
    peaks = np.array([chunk.max() for chunk in chunks])
    peaks = peaks / max(peaks.max(), 1e-6)
    return ''.join(
        f'<rect x="{i * 3}" y="{20 - max(h, 0.03) * 20:.1f}" width="2" height="{max(h, 0.03) * 40:.1f}" rx="1"/>'
        for i, h in enumerate(peaks)
    )


def font_face(weight, name):
    path = ROOT / 'node_modules' / '@expo-google-fonts' / 'poppins' / name / f'Poppins_{name}.ttf'
    data = base64.b64encode(path.read_bytes()).decode()
    return f"@font-face{{font-family:Poppins;font-weight:{weight};src:url(data:font/ttf;base64,{data})}}"


def describe(folder, name):
    audio, rate = sf.read(folder / f'{name}.wav')
    return {
        'ms': round(len(audio) / rate * 1000), 'peak': round(peak_dbfs(audio), 1),
        'loud': round(active_loudness(audio, rate), 1), 'wave': waveform(audio),
        'audio': base64.b64encode((folder / f'{name}.m4a').read_bytes()).decode(),
    }


def haptic_words(event):
    haptic = event['haptic']
    if haptic.startswith('signature:'):
        name = haptic.split(':')[1]
        return f"{CONFIG['signatures'][name]['words']} (<code>{name}.ahap</code>)"
    return CONFIG['haptic_words'][haptic]


def write_preview():
    build = Path(__file__).parent / '.build'
    data = {name: describe(build / 'kit', name) for name in SOUNDS}
    takes = {}
    for key in CONFIG['takes']['done']:
        data[f'cs-done-{key}'] = describe(build / 'takes', f'cs-done-{key}')
    takes['cs-done'] = {
        'active': CONFIG['active_takes']['done'], 'uses': SOUNDS['cs-done']['uses'], 'name': SOUNDS['cs-done']['name'],
        'takes': {key: {'label': t['label'], 'words': t['words']} for key, t in CONFIG['takes']['done'].items()},
    }
    sounds = [
        {'file': file, 'name': spec['name'], 'on': file in CONFIG['default_on'],
         'uses': [e['label'] for e in EVENTS if e['sound'] == file]}
        for file, spec in SOUNDS.items()
    ]
    events = [
        {'label': e['label'], 'id': e['id'], 'name': SOUNDS[e['sound']]['name'] if e['sound'] else None,
         'haptic': haptic_words(e), 'area': e['area']}
        for e in EVENTS
    ]
    template = (Path(__file__).parent / 'preview-template.html').read_text()
    page = (
        template.replace('/*FONTS*/', font_face(400, '400Regular') + font_face(500, '500Medium') + font_face(600, '600SemiBold'))
        .replace('/*DATA*/{}', json.dumps(data))
        .replace('/*TAKES*/{}', json.dumps(takes))
        .replace('/*SOUNDS*/[]', json.dumps(sounds))
        .replace('/*EVENTS*/[]', json.dumps(events, ensure_ascii=False))
    )
    out = ROOT / 'preview'
    out.mkdir(exist_ok=True)
    (out / 'index.html').write_text(page)
    print(f'preview/index.html {len(page) / 1024:.0f} KB')


if __name__ == '__main__':
    write_ahap()
    write_typescript()
    write_spec_table()
    write_preview()
